"""Copy the session's own figures kept in git from figures/full/ into figures/, downscaled, as JPEG
(quality 85: the micrographs are noise-limited and barely compress as PNG; repo environment,
needs Pillow).

    python publish_figures.py

The full-resolution originals in figures/full/ are regenerated by the other scripts and not in
git. The standard figures (overview, upsampling_*) are written straight to figures/ by
scripts/session_report.py."""
from PIL import Image

from paths import FIGURES, FULL

KEEP = {  # figures/full/<name>.png → figures/<name>.jpg at this width (px)
    "realtime_stem_vs_quantem_binned": 2600,
    "frame_mean_dc_upsampling_binned": 1500,
    "binned_vs_unbinned": 1800,
    "midscan_binned_x4": 1600,
    "frame_mean": 1700,
    "continuous_modes": 2600,
}
for name, width in KEEP.items():
    im = Image.open(FULL / f"{name}.png").convert("RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    out = FIGURES / f"{name}.jpg"
    im.save(out, quality=85, optimize=True, progressive=True)
    print(f"{out.name}: {im.width}×{im.height}, {out.stat().st_size / 1e6:.2f} MB")
