"""Copy the figures kept in git into analysis/figures/, downscaled, as JPEG (quality 85: the
micrographs are noise-limited and barely compress as PNG) except the line plots (repo environment,
needs Pillow).

    python publish_figures.py

The full-resolution originals in analysis/ are regenerated by the other scripts and not in git."""
from PIL import Image

from paths import ANALYSIS, FIGURES

KEEP = {  # source (analysis/) → (name in figures/, width in px)
    "cal_binned.png": ("calibration_binned.png", 2000),
    "overview.png": ("overview.jpg", 1800),
    "B1_methods_binned.png": ("realtime_stem_vs_quantem_binned.jpg", 2600),
    "B2_variants_binned.png": ("frame_mean_dc_upsampling_binned.jpg", 1500),
    "B3_binned_vs_unbinned.png": ("binned_vs_unbinned.jpg", 1800),
    "B4_midscan_binned_U4.png": ("midscan_binned_x4.jpg", 1600),
    "B5_frame_mean.png": ("frame_mean.jpg", 1700),
    "C_compare_modes.png": ("continuous_modes.jpg", 2600),
}
FIGURES.mkdir(exist_ok=True)
for src, (name, width) in KEEP.items():
    im = Image.open(ANALYSIS / src).convert("RGB")
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    if name.endswith(".jpg"):
        im.save(FIGURES / name, quality=85, optimize=True, progressive=True)
    else:
        im.save(FIGURES / name, optimize=True)
    print(f"{name}: {im.width}×{im.height}, {(FIGURES / name).stat().st_size / 1e6:.2f} MB")
